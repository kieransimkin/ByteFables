#!/usr/bin/env node
/**
 * Rebuild the immutable v1 lexicon bundle from six pinned user-researched text
 * files. CI runs --check and fails if any source or output has changed.
 * Published indexes are a wire format: intentionally NEVER sort these lists.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = resolve(fileURLToPath(new URL('..', import.meta.url)));
const dir = 'src/grammar/wordlists/large-v1';
const output = resolve(root, 'src/grammar/large-lexicon-data-v1.ts');
const expected = Object.freeze({
  nouns: { count: 16396, us: 'abd6bca3958737e908ae48ea57f56eda93d0295f6858cf08867ccdb3850cdb2a', gb: '88f9adb43c19eed0a70e6b0278fc0ea1ad171279d88845ec8795dc258b3d707e' },
  adjectives: { count: 10569, us: 'cc1e2bad91eead448abc59f77acf04d19a78a36573f44de5db6831607b9f0992', gb: '0da48b79ea590486363d10412b012fb850ef4a593d80531bc2869f5eb4de1565' },
  verbs: { count: 3554, us: '6b81ff7844c2c4733a39d4f8b3f4cf9d8ae084624a33279241545a9dd2a8bcfc', gb: 'd208a8aab7b8a56956e706a50d1bfbed48ee3a569cde6b2ea8a47a6a4923b379' }
});

function readRole(role, locale, expectedHash, count) {
  const data = readFileSync(resolve(root, dir, `${role}.${locale}.txt`));
  const hash = createHash('sha256').update(data).digest('hex');
  if (hash !== expectedHash) throw new Error(`${role}.${locale} SHA-256 changed: breaking wire-format update`);
  const content = data.toString('utf8');
  if (!content.endsWith('\n') || content.includes('\r') || content.includes('\uFFFD')) throw new Error('Invalid LF UTF-8 source');
  const rows = content.slice(0, -1).split('\n');
  if (rows.length !== count || new Set(rows).size !== count ||
      rows.some(w => !/^[a-z]+$/.test(w))) throw new Error(`Invalid or duplicate entries in ${role}.${locale}`);
  return rows;
}

const bundles = [];
for (const [role, { count, us, gb }] of Object.entries(expected)) {
  const american = readRole(role, 'en-us', us, count);
  const british = readRole(role, 'en-gb', gb, count);
  const rows = american.map((w, i) => w === british[i] ? w : `${w}|${british[i]}`);
  bundles.push([role, rows.join('\n')]);
}
const file = [
  '/** GENERATED by scripts/generate-lexicons-v1.mjs. DO NOT EDIT. */',
  '/** Index order is part of the experimental large-story v1 wire format. */',
  'export const LARGE_LEXICON_DATA_V1 = Object.freeze({',
  ...bundles.map(([role, content]) => `  ${role}: \`${content}\`,`),
  '} as const);',
  ''
].join('\n');
if (process.argv.slice(2).includes('--check')) {
  if (readFileSync(output, 'utf8') !== file) throw new Error('Generated lexicon bundle out of sync with pinned lists');
  console.log('Large lexicon v1 source SHA-256, sizes, uniqueness and generated bundle verified');
} else {
  writeFileSync(output, file, 'utf8');
  console.log(`Generated ${output}`);
}
